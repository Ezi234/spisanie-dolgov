  const TOPICS = ['Подхожу ли я?', 'Сколько стоит?', 'Сколько длится?', 'Что будет с квартирой?', 'Какие долги спишут?', 'Какие последствия?'];

  /* ---------- ДА / НЕТ ---------- */
  function yesNo(t) {
    const s = norm(t).replace(/[^a-zа-я ]/g, ' ').trim();
    if (/^(да|ага|угу|конечно|давайте|давай|хочу|можно|верно|точно|yes|ок|окей|хорошо|подскажите|да,? \S+|проверить|да проверить|закрыли|да закрыли)( |$)/.test(s)) return 'yes';
    if (/^(нет|неа|не надо|не нужно|не хочу|no|не закрывали|нет еще)( |$)/.test(s)) return 'no';
    if (/(не знаю|незнаю|хз|без понятия|не помню|не уверен)/.test(s)) return 'unknown';
    return null;
  }

  /* ---------- ВЫБОР ТЕМЫ ---------- */
  function score(text) {
    const toks = words(text);
    const res = [];
    for (const it of KB) {
      let sc = 0;
      for (const k of it.kw) {
        const pat = Array.isArray(k) ? k[0] : k;
        const w = Array.isArray(k) ? k[1] : 2;
        if (phraseHits(toks, pat)) sc += w;
      }
      if (sc > 0) res.push({ it, sc });
    }
    res.sort((a, b) => b.sc - a.sc);
    return res;
  }
  function facts(text) {
    const toks = words(text);
    const f = {};
    for (const k in FACTS) if (FACTS[k].some((p) => phraseHits(toks, p))) f[k] = true;
    return f;
  }

  /* ---------- БОТ ---------- */
  function create(opts) {
    opts = opts || {};
    const now = opts.now || (() => new Date());
    const st = opts.state || { amount: null, facts: {}, props: {}, seen: {}, misses: 0, pending: null, name: null, questions: [], last: null, greeted: false, phone: null };

    const pick = (arr, id) => {
      const n = st.seen[id] || 0;
      return arr[n % arr.length];
    };
    const ctxFor = (text, factsNow) => {
      const w = work(now());
      return { text: norm(text), work: w, hello: hello(now()), amount: st.amount, factsNow, repeat: (st.seen.debts || 0) > 0 };
    };
    const offHours = (w) => w.open
      ? 'Сейчас юристы на связи — ответят в ближайшее время.'
      : 'Сейчас нерабочее время (юристы на связи с ' + CFG.workStart + ':00 до ' + CFG.workEnd + ':00 по Москве), поэтому юрист ответит **' + w.next + '**.';

    function draft() {
      const lines = ['Здравствуйте! ' + (st.name ? 'Меня зовут ' + st.name + '. ' : '') + 'Пишу с сайта, хочу консультацию по списанию долгов.'];
      if (st.amount) lines.push('Сумма долгов: около ' + fmt(st.amount) + '.');
      const debts = Object.keys(st.facts).filter((k) => FACT_NAMES[k]).map((k) => FACT_NAMES[k]);
      if (debts.length) lines.push('Долги: ' + debts.join(', ') + '.');
      const props = Object.keys(st.props).map((k) => PROP_NAMES[k]);
      if (props.length) lines.push('Имущество: ' + props.join(', ') + '.');
      if (st.facts.pension) lines.push('Я пенсионер.');
      if (st.facts.fssp) lines.push('Есть исполнительное производство у приставов.');
      const qs = st.questions.slice(-2);
      if (qs.length) lines.push('Мой вопрос: ' + qs.join(' / '));
      if (st.phone) lines.push('Мой телефон: ' + st.phone + '.');
      return lines.join('\n');
    }

    function handoffStart() {
      const w = work(now());
      if (st.name) return handoffCard();
      st.pending = 'name';
      return [{ text: 'Конечно, передам ваш вопрос юристу. ' + offHours(w) + '\nКак к вам обращаться?', quick: ['Пропустить'] }];
    }
    function handoffCard() {
      const w = work(now());
      st.pending = null;
      st.handed = true;
      return [{
        text: (st.name ? st.name + ', с' : 'С') + 'обрал сообщение для юриста — проверьте и отправьте удобным способом. В МАКС и ВКонтакте текст скопируется сам, останется вставить его в чат.\n' +
          (w.open ? 'Сейчас юристы на связи — ответят в ближайшее время.' : 'Сообщение придёт сразу, а **ответим ' + w.next + '** — сейчас нерабочее время.'),
        card: { type: 'handoff', message: draft() }
      }];
    }

    function answer(item, text, f, prefix) {
      const c = ctxFor(text, f);
      let out = null;
      if (item.route && st.amount) out = routeAdvice(st.amount, st);
      if (!out) {
        let a = typeof item.a === 'function' ? item.a(c) : item.a;
        if (!a) return null;
        if (!Array.isArray(a)) a = [a];
        out = { text: pick(a, item.id), quick: item.quick };
        if (item.after) item.after(st);
      }
      st.seen[item.id] = (st.seen[item.id] || 0) + 1;
      if (prefix) out.text = prefix + out.text;
      return out;
    }

    function quickFor(q) {
      const list = (q || []).slice(0, 3);
      if (list.indexOf(LAWYER) < 0 && !st.handed && list.length < 4) list.push(LAWYER);
      return list;
    }

    // Короткая подсказка по сумме — когда человек спросил о другом, но сумму назвал
    function routeHint(a) {
      const x = fmt(a);
      if (a < 25000) return 'При долге около ' + x + ' банкротство обычно невыгодно — проще договориться с кредитором о рассрочке.';
      if (a > 1000000) return 'При долге около ' + x + ' подходит только судебная процедура: через МФЦ списывают до 1 000 000 ₽.';
      return 'При долге около ' + x + ' возможен и бесплатный путь через МФЦ — если приставы окончили исполнительное производство, потому что взыскать нечего.';
    }
    const msg = (text, quick) => ({ text, quick: quick === null ? [] : quickFor(quick) });
    const rememberQ = (text) => {
      st.questions.push(text.length > 160 ? text.slice(0, 157) + '…' : text);
      if (st.questions.length > 4) st.questions.shift();
    };
    const byId = (id) => KB.find((x) => x.id === id);
    const SOCIAL = /^(greet|thanks|bye|smalltalk|rude|offtopic|otherlaw|bot)$/;
    const SITUATION = /^(greet|cantpay|eligible|what|flat|car|mortgage|family|income|debts|collectors)$/;

    function reply(raw) {
      const text = String(raw || '').slice(0, 1000).trim();
      if (!text) return [];
      const n = norm(text).trim();
      const f = facts(text);
      let amt = AMOUNT_QR_VALUES[n] || parseAmount(text);
      // ответ на «какая сумма?» просто числом: «300» — это 300 тысяч
      if (!amt && st.pending === 'amount') {
        const m = n.match(/^[^\d]*(\d{1,3}(?:[.,]\d)?)[^\d]*$/);
        if (m) amt = Math.round(parseFloat(m[1].replace(',', '.')) * 1000);
      }
      if (amt) st.amount = amt;
      for (const k in f) { if (PROP_NAMES[k]) st.props[k] = true; else st.facts[k] = true; }
      const phone = text.match(/(\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/);
      if (phone) st.phone = phone[0].replace(/\s+/g, ' ');

      const yn = yesNo(text);
      const scored = score(text);
      const top = scored[0];
      const strong = !!(top && top.sc >= 3);

      /* 1. Ждём ответ на свой вопрос */
      if (st.pending === 'name') {
        if (n === 'пропустить' || yn === 'no') return handoffCard();
        if (!strong || top.it.id === 'greet') {
          const name = text.replace(/^(меня зовут|зовут|я|это|мое имя|моё имя)\s+/i, '').replace(/[^A-Za-zА-Яа-яЁё\- ]/g, '').trim().split(/\s+/).slice(0, 2).join(' ');
          if (name.length >= 2 && name.length <= 30) {
            st.name = name.charAt(0).toUpperCase() + name.slice(1);
            return handoffCard();
          }
        }
        st.pending = null;                       // человек спросил о другом — отвечаем по теме
      }
      if (st.pending === 'amount') {
        if (amt) { st.pending = null; st.misses = 0; const r = routeAdvice(amt, st); return [msg(r.text, r.quick)]; }
        if (yn === 'unknown') {
          return [{ text: 'Ничего страшного. Точную сумму всех долгов видно в кредитной истории — её бесплатно выдают бюро кредитных историй (запрос через Госуслуги). А пока ответьте примерно:', quick: AMOUNT_QR }];
        }
      }
      if (st.pending === 'fssp' && (yn || /закрыл|окончен|прекращ/.test(n)) && !(strong && !/^(thanks|checkfssp)$/.test(top.it.id))) {
        st.pending = null;
        if (yn === 'unknown' || /как проверить/.test(n)) {
          const r = answer(byId('checkfssp'), text, f);
          st.pending = 'fssp';
          return [msg(r.text + '\nКогда проверите, напишите — закрыто производство или нет.', ['Да, закрыли', 'Нет'])];
        }
        if (yn === 'yes' || /закрыли|окончен/.test(n)) {
          return [msg('Тогда, скорее всего, вам подходит **бесплатное банкротство через МФЦ** — важно только, чтобы не было новых открытых производств. Процедура длится 6 месяцев, после этого долги списываются.\nЮрист может бесплатно проверить ваши данные и помочь с заявлением.', ['Какие долги спишут?', 'Что будет с квартирой?'])];
        }
        const pens = st.facts.pension
          ? ' Но вы пенсионер — для вас МФЦ возможен, если производство открыто больше года и долг не погашен.'
          : ' Исключение — пенсионеры: им подойдёт и открытое производство, если оно идёт больше года.';
        return [msg('Тогда МФЦ пока не подойдёт.' + pens + '\nОстаётся **судебное банкротство**: оно подходит при любой сумме и обычно занимает 6–9 месяцев.', ['Сколько стоит?', 'Что будет с имуществом?'])];
      }
      if ((st.pending === 'yesAmount' || st.pending === 'handoff') && yn && !(strong && top.it.id !== 'thanks')) {
        const p = st.pending;
        st.pending = null;
        if (yn === 'yes') {
          if (p === 'handoff') return handoffStart();
          if (st.amount) { const r = routeAdvice(st.amount, st); return [msg(r.text, r.quick)]; }
          st.pending = 'amount';
          return [{ text: 'Какая у вас общая сумма долгов? Можно примерно.', quick: AMOUNT_QR }];
        }
        return [msg('Хорошо. Задайте вопрос своими словами или выберите тему:', TOPICS.slice(0, 3))];
      }
      if (st.pending && st.pending !== 'name') st.pending = null;

      /* 2. Кнопка быстрого ответа или тема по словам */
      const qid = QR_MAP[n];
      let items = [];
      if (qid) items = [byId(qid)];
      else if (strong) {
        items = [top.it];
        const second = scored[1];
        // вторая тема, если вопрос двойной: «что будет с квартирой и машиной?»
        if (second && second.sc >= 4 && second.sc >= top.sc * 0.6 && !SOCIAL.test(second.it.id) && !SOCIAL.test(top.it.id)) items.push(second.it);
      }
      // приветствие или «спасибо» рядом с вопросом — отвечаем на вопрос
      let prefix = scored.some((x) => x.it.id === 'greet' && x.sc >= 3) && items.length && items[0].id !== 'greet' ? hello(now()) + '! ' : '';
      if (items.length && /^(greet|thanks)$/.test(items[0].id)) {
        const rest = scored.filter((s) => !/^(greet|thanks)$/.test(s.it.id) && s.sc >= 3);
        if (rest.length || amt) {
          if (items[0].id === 'greet') prefix = hello(now()) + '! ';
          items = rest.length ? [rest[0].it] : [];
        }
      }
      // ипотека важнее общего «квартира»; про машину квартира расскажет сама
      if (f.mortgage) items = items.map((x) => (x.id === 'flat' ? byId('mortgage') : x));
      if (items.some((x) => x.id === 'flat') && f.car) items = items.filter((x) => x.id !== 'car');
      items = items.filter((x, i, arr) => x && arr.findIndex((y) => y.id === x.id) === i);

      if (!qid && !yn && (items.length ? !SOCIAL.test(items[0].id) && !items[0].handoff : true)) rememberQ(text);
      if (items.length && items[0].handoff) { st.misses = 0; return handoffStart(); }

      /* 3. Собираем ответ */
      const parts = [];
      let quick = null;
      const situational = !items.length || items.every((x) => SITUATION.test(x.id));
      for (const it of items) {
        if (amt && /^(greet|cantpay|eligible|what)$/.test(it.id)) continue;   // их заменит совет по сумме
        const r = answer(it, text, f, parts.length ? '' : prefix);
        if (r) { parts.push(r.text); quick = r.quick; }
      }
      if (amt && !qid) {
        // сумма в сообщении: при описании ситуации — полный совет (в конце, чтобы вопрос был последним),
        // при конкретном вопросе — одна строка подсказки
        if (situational) {
          if (!parts.length && prefix) parts.push(prefix.trim());
          if (f.alimony && !items.some((x) => x.id === 'debts')) parts.push('Учтите: алименты не списываются — их придётся платить и после банкротства.');
          const r = routeAdvice(amt, st);
          parts.push(r.text);
          quick = r.quick;
        } else {
          parts.push(routeHint(amt));
        }
      }
      if (parts.length) {
        st.misses = 0;
        st.last = items.length ? items[0].id : 'route';
        const social = items.length && /^(thanks|bye)$/.test(items[0].id);
        return [msg(parts.join('\n\n'), social ? null : quick)];
      }

      if (yn && !items.length) {
        if (yn === 'no') return [msg('Хорошо. Если появятся вопросы — пишите, я на связи.', null)];
        if (yn === 'unknown') return [msg('Ничего страшного. Расскажите своими словами, что вас беспокоит, — разберёмся вместе.', TOPICS.slice(0, 3))];
        return [{ text: 'Слушаю вас — задайте вопрос своими словами или выберите тему:', quick: TOPICS }];
      }

      /* 4. Тема не найдена, но названы виды долгов — тоже ответ */
      if (Object.keys(f).some((k) => FACT_NAMES[k])) {
        st.misses = 0;
        const d = answer(byId('debts'), text, f, prefix);
        if (st.amount) return [msg(d.text, d.quick)];
        st.pending = 'amount';
        return [{ text: d.text, quick: [] }, { text: 'Чтобы подсказать путь, напишите общую сумму долгов — можно примерно.', quick: AMOUNT_QR }];
      }

      /* 5. Не поняли: сначала уточняем, на второй раз предлагаем юриста */
      st.misses++;
      if (st.misses >= 2) {
        st.pending = 'handoff';
        return [{ text: 'Похоже, у вас непростой вопрос — такие лучше разобрать с юристом, это бесплатно. Передать ему ваш вопрос?', quick: ['Да, передайте юристу', 'Нет, спрошу иначе'] }];
      }
      const miss = pick(['Не уверен, что правильно понял. Уточните, пожалуйста, вопрос — или выберите тему:', 'Простите, не совсем понял вас. Попробуйте сформулировать иначе или выберите тему ниже:'], '_miss');
      st.seen._miss = (st.seen._miss || 0) + 1;
      return [{ text: miss, quick: TOPICS }];
    }

    function start() {
      const w = work(now());
      st.greeted = true;
      const base = hello(now()) + '! Я виртуальный помощник по банкротству физических лиц. Отвечу на вопросы о списании долгов: сколько стоит, сколько длится, что будет с имуществом и подходит ли вам бесплатная процедура через МФЦ.\n' +
        'Напишите, что у вас случилось, или выберите тему.';
      const after = w.open ? '' : '\n\nСейчас нерабочее время — юристы на связи с ' + CFG.workStart + ':00 до ' + CFG.workEnd + ':00 по Москве. Я отвечу на вопросы сейчас, а юрист прочитает ваше сообщение и ответит **' + w.next + '**.';
      return [{ text: base + after, quick: ['Подхожу ли я?', 'Сколько стоит?', 'Сколько длится?', 'Что будет с квартирой?', 'Через МФЦ бесплатно'] }];
    }

    return { start, reply, state: st, draft, work: () => work(now()) };
  }

  const api = { create, parseAmount, work, CFG, _score: score, _facts: facts };
