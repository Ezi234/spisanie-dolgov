  function tokenHits(tok, pat) {
    if (pat instanceof RegExp) return pat.test(tok);
    if (pat.endsWith('=')) return tok === pat.slice(0, -1);
    if (tok.startsWith(pat)) return true;
    // первую букву люди почти не путают — без этого «платить» сходилось бы с «оплат»
    if (pat.length >= 5 && tok.length >= pat.length - 1 && tok[0] === pat[0]) {
      for (let k = pat.length - 1; k <= pat.length + 1; k++) {
        if (dist(tok.slice(0, k), pat) <= 1) return true;
      }
    }
    return false;
  }
